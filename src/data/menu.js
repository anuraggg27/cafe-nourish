// Helper: filter menu by category/tag
export function filterMenu(items, activeFilter) {
  if (!activeFilter || activeFilter === "all" || activeFilter === "All") return items;
  const f = activeFilter.toLowerCase();
  // category match
  if (["breakfast", "lunch", "snacks", "drinks"].includes(f)) {
    return items.filter(i => i.category.toLowerCase() === f);
  }
  // tag match
  return items.filter(i => i.tags.includes(f));
}

// Helper: get item by id
export function getMenuItemById(id) {
  return menuItems.find(i => i.id === id) || null;
}

